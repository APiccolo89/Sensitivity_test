"""
---
This is a small script that runs the time-dependent sensitivity tests.
I divided the tests into 2 main categories and three subcategories. The main categories are:
shear heating and no shear heating. The subcategories are: linear thermal properties with k=3.1,
linear thermal properties with k=5.0 and non-linear thermal properties.
Each of the six subcategories has different individual cases, and these cases are an array of
parameters generated by combining different values of convergence velocity and slab age.
---
The categories are defined using a dictionary, while the individual cases are read from a .csv table.
The script has the following input arguments:
    --case_index: the index of the group to run; this is an integer that corresponds to the row of the .csv table.
    --group: the name of the group to run; this is a string that corresponds to the key of the dictionary.
    --id_batch: the id of the batch; this is an integer that corresponds to the batch of cases to run.
    --steady_state: a flag that indicates whether to run the test in steady-state or time-dependent mode.
      This is an integer that can be 0 or 1.
---
The script is designed to be run together with a bash submission script. This bash submission script is
an array job of 100 processors. The bash submission script is designed to have one processor dealing
with a certain number of cases (in the time-dependent group, the numbers of processors and cases are
the same). In general, the design is to be able to identify the id_batch with the processor number.
For example, in the group of the steady-state sensitivity tests, the 7000 cases have been divided into
100 batches of 70 cases each, and each batch is responsible for a small array of cases:
(0:100:6900 for pr0, and so forth).
---
The string defining the group is converted into the shear-heating option and a thermal conductivity value.
I use the conductivity value not only as a value, but also assign it the role of defining the material
properties. So, during the pre-processing of the script, the k value is used to create a multi-level
dictionary that assigns the material properties of the phases: if k is 3.1 or 5.0, the material properties
are linear and constant, while if k is negative, the material properties are non-linear and
temperature-dependent. The creation of this dictionary is not customizable by the user, but is hard-coded
in the script. However, this can represent a blueprint for defining the material properties in a more
general way. In this project, it was convenient to generate this dictionary. Or at least it is a way that
I liked.
---
After running the test, the script saves the results in a folder, in a number of h5 files that will be
merged by other scripts.
"""

